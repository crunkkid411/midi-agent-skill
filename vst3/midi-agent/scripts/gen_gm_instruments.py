#!/usr/bin/env python3
"""Regenerate core/gm_instruments.cpp from midi_types/gm_instruments.py.

Run from the repository root:
    python vst3/midi-agent/scripts/gen_gm_instruments.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from midi_types.gm_instruments import GM_INSTRUMENTS, INSTRUMENT_ALIASES  # noqa: E402

names = [None] * 128
for key, program in GM_INSTRUMENTS.items():
    if names[program] is None:
        names[program] = key
missing = [i for i, n in enumerate(names) if n is None]
if missing:
    raise SystemExit(f"GM table has gaps: {missing}")

out = [
    "// Generated by scripts/gen_gm_instruments.py from midi_types/gm_instruments.py.",
    "// Do not edit by hand. Re-run the script when the Python table changes.",
    '#include "core/gm_instruments.h"',
    "#include <cstring>",
    "",
    "namespace midiagent {",
    "",
    "static const char* const kGmNames[128] = {",
]
out += [f'    "{n}", // {i}' for i, n in enumerate(names)]
out += ["};", "", "static const struct { const char* alias; const char* name; } kGmAliases[] = {"]
out += [f'    {{"{a}", "{n}"}},' for a, n in INSTRUMENT_ALIASES.items()]
out += [
    "    {nullptr, nullptr}",
    "};",
    "",
    "const char* gmInstrumentName (int program)",
    "{",
    "    if (program < 0 || program > 127)",
    '        return "";',
    "    return kGmNames[program];",
    "}",
    "",
    "int gmProgramForName (const std::string& name)",
    "{",
    "    if (name.empty ())",
    "        return 0;",
    "    for (int i = 0; i < 128; ++i)",
    "        if (name == kGmNames[i])",
    "            return i;",
    "    for (int i = 0; kGmAliases[i].alias != nullptr; ++i)",
    "        if (name == kGmAliases[i].alias)",
    "            return gmProgramForName (kGmAliases[i].name);",
    "    return 0;",
    "}",
    "",
    "} // namespace midiagent",
]
target = ROOT / "vst3" / "midi-agent" / "core" / "gm_instruments.cpp"
target.write_text("\n".join(out) + "\n")
print(f"wrote {target}")
